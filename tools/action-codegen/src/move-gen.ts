/**
 * Generate a complete lib/<module>.move file containing:
 * - ExecutionProgressWitness struct
 * - Marker type struct + factory function
 * - do_init_* execution function (with TODO placeholder for custom logic)
 * - (no delete_* function needed — Expired has drop)
 */
export function generateExecution(schema: ActionSchema): string {
  const lines: string[] = [];
  const pkgAddr = packageToMoveAddr(schema.package);
  const phantomTypes = getPhantomTypes(schema);
  const execFn = getExecFunctionName(schema);
  const fullMarkerType = getFullMarkerType(schema);
  const exec = schema.execution;

  // Header
  lines.push('// Copyright (c) Govex DAO LLC');
  lines.push('// SPDX-License-Identifier: BUSL-1.1');
  lines.push('');
  lines.push(`/// GENERATED by codegen — do not edit manually`);
  lines.push(`/// Execution module for ${schema.name}`);
  lines.push(`module ${pkgAddr}::${schema.module};`);
  lines.push('');
  lines.push('public struct ExecutionProgressWitness has drop {}');
  lines.push('');
  lines.push('');

  // Imports
  lines.push('use account_protocol::action_validation;');
  lines.push('use account_protocol::bcs_validation;');
  lines.push('use account_protocol::executable::{Self, Executable};');
  lines.push('use account_protocol::intents;');

  if (exec.needsAccount) {
    lines.push('use account_protocol::account::{Self, Account};');
  }
  lines.push('use account_protocol::package_registry::PackageRegistry;');
  if (exec.capBorrow) {
    lines.push('use account_actions::access_control;');
  }

  const usesResources = schema.fields.some(
    (f) => isResourceIn(f.role) || isResourceOut(f.role),
  );
  if (usesResources) {
    lines.push('use account_protocol::executable_resources;');
  }

  // Standard imports based on field types
  const typesUsed = fieldTypesUsed(schema.fields);
  if (typesUsed.has('Option')) {
    lines.push('use std::option::{Self, Option};');
  }
  if (typesUsed.has('String')) {
    lines.push('use std::string::String;');
  }
  if (typesUsed.has('ID') || exec.externalObjects?.length) {
    lines.push('use sui::object::{Self, ID};');
  }
  lines.push('use sui::bcs;');
  if (exec.needsClock) {
    lines.push('use sui::clock::Clock;');
  }
  if (requiresCtx(schema)) {
    lines.push('use sui::tx_context::TxContext;');
  }

  lines.push('');

  // Errors
  lines.push('// === Errors ===');
  lines.push('');
  lines.push('const EUnsupportedActionVersion: u64 = 0;');
  if (exec.externalObjects?.length) {
    lines.push('const EExternalObjectMismatch: u64 = 1;');
  }
  lines.push('');

  // Marker type struct + factory
  lines.push('// === Action Type Markers ===');
  lines.push('');
  if (schema.description) {
    lines.push(`/// ${schema.description}`);
  }
  if (phantomTypes.length > 0) {
    const phantomParams = phantomTypes.map((t) => `phantom ${t}`).join(', ');
    lines.push(`public struct ${schema.marker.name}<${phantomParams}> has drop {}`);
    lines.push('');
    const factoryTypeParams = `<${phantomTypes.join(', ')}>`;
    const factoryName = getMarkerFactoryName(schema);
    lines.push(
      `public(package) fun ${factoryName}${factoryTypeParams}(): ${schema.marker.name}${factoryTypeParams} { ${schema.marker.name} {} }`,
    );
  } else {
    lines.push(`public struct ${schema.marker.name} has drop {}`);
    lines.push('');
    const factoryName = getMarkerFactoryName(schema);
    lines.push(
      `public(package) fun ${factoryName}(): ${schema.marker.name} { ${schema.marker.name} {} }`,
    );
  }
  lines.push('');

  // === Execution function ===
  lines.push('// === Public Functions ===');
  lines.push('');
  lines.push(`/// Execute ${schema.name} action`);

  // Build function signature
  const execTypeParams = buildExecTypeParams(schema);
  const execParams = buildExecParams(schema);

  lines.push(`public fun ${execFn}${execTypeParams}(`);
  for (const p of execParams) {
    lines.push(`    ${p},`);
  }
  lines.push(') {');

  // Function body: boilerplate
  if (exec.needsAccount) {
    lines.push(
      '    account::assert_execution_authorized(account, registry, executable, ExecutionProgressWitness {});',
    );
    lines.push('');
  }

  // Get ActionSpec
  lines.push('    // Get BCS bytes from ActionSpec');
  lines.push('    let specs = executable.intent().action_specs();');
  lines.push('    let action_spec = specs.borrow(executable.action_idx());');
  lines.push(`    action_validation::assert_action_type<${fullMarkerType}>(action_spec);`);
  lines.push('');

  // Get action data and version
  lines.push('    let action_data = intents::action_spec_data(action_spec);');
  lines.push('');
  lines.push('    // Check version before deserialization');
  lines.push('    let spec_version = intents::action_spec_version(action_spec);');
  lines.push(`    assert!(spec_version == ${schema.version}, EUnsupportedActionVersion);`);
  lines.push('');

  // BCS deserialization
  lines.push('    // Create BCS reader and deserialize');
  lines.push('    let mut reader = bcs::new(*action_data);');
  for (const field of schema.fields) {
    emitBcsPeel(lines, field);
  }
  lines.push('');

  // Validate all bytes consumed
  lines.push('    // Validate all bytes consumed');
  lines.push('    bcs_validation::validate_all_bytes_consumed(reader);');
  lines.push('');

  // Validate external object IDs
  if (exec.externalObjects?.length) {
    lines.push('    // Validate external object IDs match staged values');
    for (const obj of exec.externalObjects) {
      lines.push(
        `    assert!(object::id(${obj.name}) == ${obj.idField}, EExternalObjectMismatch);`,
      );
    }
    lines.push('');
  }

  // Take resources from executable_resources (resource_in_* fields)
  const resInFields = schema.fields.filter((f) => isResourceIn(f.role));
  if (resInFields.length > 0) {
    lines.push('    // Take resources from executable_resources');
    for (const field of resInFields) {
      const role = normalizeRole(field.role)!;
      const varName = resourceLocalName(field, role);
      const moveType = resourceMoveType(field, role, phantomTypes);
      if (role === 'resource_in_coin') {
        lines.push(`    let ${varName}: ${moveType} = executable_resources::take_coin(`);
        lines.push('        executable,');
        lines.push('        registry,');
        lines.push('        ExecutionProgressWitness {},');
        lines.push(`        ${field.name},`);
        lines.push('    );');
      } else if (role === 'resource_in_object') {
        lines.push(`    let ${varName}: ${moveType} = executable_resources::take_object(`);
        lines.push('        executable,');
        lines.push('        registry,');
        lines.push('        ExecutionProgressWitness {},');
        lines.push(`        ${field.name},`);
        lines.push('    );');
      }
    }
    lines.push('');
  }

  // Execution logic
  const resOutFields = schema.fields.filter((f) => isResourceOut(f.role));
  const hasReturn = resOutFields.length > 0;

  if (exec.capBorrow && schema.wrappedCall) {
    generateCapBorrowWithWrappedCall(lines, exec.capBorrow, schema.wrappedCall, hasReturn);
  } else if (exec.capBorrow) {
    generateCapBorrow(lines, exec.capBorrow);
    lines.push('');
    lines.push(
      '    // ========== EXECUTION LOGIC (HAND-WRITTEN) ==========',
    );
    lines.push(`    // Cap is available as "${exec.capBorrow.varName}" (passStyle: ${exec.capBorrow.passStyle})`);
    lines.push(
      '    // ====================================================',
    );
    lines.push('');
    generateCapReturn(lines, exec.capBorrow);
  } else if (schema.wrappedCall) {
    generateWrappedCall(lines, schema.wrappedCall, hasReturn);
  } else {
    lines.push(
      '    // ========== EXECUTION LOGIC (HAND-WRITTEN) ==========',
    );
    lines.push('    // TODO: Implement execution logic here');
    lines.push(
      '    // ====================================================',
    );
  }
  lines.push('');

  // Provide resources to executable_resources (resource_out_* fields)
  if (resOutFields.length > 0) {
    lines.push('    // Provide resources to executable_resources');
    for (const field of resOutFields) {
      const role = normalizeRole(field.role)!;
      // When wrappedCall is present, the call result var is `call_result`
      const resultVar = schema.wrappedCall ? 'call_result' : 'result_out';
      if (role === 'resource_out_coin') {
        lines.push(`    executable_resources::provide_coin(`);
        lines.push('        executable,');
        lines.push('        registry,');
        lines.push('        ExecutionProgressWitness {},');
        lines.push(`        ${field.name},`);
        lines.push(`        ${resultVar},`);
        lines.push('        ctx,');
        lines.push('    );');
      } else if (role === 'resource_out_object') {
        lines.push(`    executable_resources::provide_object(`);
        lines.push('        executable,');
        lines.push('        registry,');
        lines.push('        ExecutionProgressWitness {},');
        lines.push(`        ${field.name},`);
        lines.push(`        ${resultVar},`);
        lines.push('        ctx,');
        lines.push('    );');
      }
    }
    lines.push('');
  }

  // Increment action index
  lines.push(
    `    executable::increment_action_idx<_, ${fullMarkerType}, _>(executable, registry, ExecutionProgressWitness {});`,
  );
  lines.push('}');
  lines.push('');

  // No delete_* function needed — Expired has drop

  return lines.join('\n');
}

