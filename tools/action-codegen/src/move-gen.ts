/** Build parameter list for spec builder function */
function buildSpecParams(schema: ActionSchema): string[] {
  const params: string[] = [];
  for (const field of schema.fields) {
    const moveType = MOVE_TYPE_MAP[field.type].moveType;
    params.push(`${field.name}: ${moveType}`);
  }
  return params;
}

/** Build type params for the staging function. */
function buildSpecTypeParams(schema: ActionSchema): string {
  const phantoms = getPhantomTypes(schema);
  if (phantoms.length === 0) return '';
  const params = phantoms.map((phantom) => {
    const constraints = schema.execution.typeParamConstraints?.[phantom];
    return constraints && constraints.length > 0
      ? `${phantom}: ${constraints.join(' + ')}`
      : phantom;
  });
  return `<${params.join(', ')}>`;
}

/** Build type params string for execution function */
function buildExecTypeParams(schema: ActionSchema): string {
  const parts: string[] = [];
  const exec = schema.execution;

  // Config is needed when the function operates on Account-managed data (e.g. vaults)
  if (exec.needsAccount) {
    const constraints = exec.typeParamConstraints?.Config;
    parts.push(`Config: ${constraints && constraints.length > 0 ? constraints.join(' + ') : 'store'}`);
  }

  parts.push('Outcome: store');

  // Add phantom types from marker
  const phantoms = getPhantomTypes(schema);
  for (const phantom of phantoms) {
    if (exec.needsAccount && phantom === 'Config') continue;
    const constraints = exec.typeParamConstraints?.[phantom];
    if (constraints && constraints.length > 0) {
      parts.push(`${phantom}: ${constraints.join(' + ')}`);
    } else {
      parts.push(phantom);
    }
  }

  parts.push('IW: drop');

  return `<${parts.join(', ')}>`;
}

/** Build parameter list for execution function */
function buildExecParams(schema: ActionSchema): string[] {
  const params: string[] = [];
  const exec = schema.execution;

  params.push('executable: &mut Executable<Outcome>');

  if (exec.needsAccount) {
    params.push('account: &mut Account');
  }
  params.push('registry: &PackageRegistry');

  // External objects
  if (exec.externalObjects) {
    for (const obj of exec.externalObjects) {
      const mutPrefix = obj.mutable ? '&mut ' : '&';
      params.push(`${obj.name}: ${mutPrefix}${obj.type}`);
    }
  }

  if (exec.needsClock) {
    params.push('clock: &Clock');
  }

  params.push('_intent_witness: IW');

  if (requiresCtx(schema)) {
    params.push('ctx: &mut TxContext');
  }

  return params;
}

/** Emit a BCS peel block for a field. */
function emitBcsPeel(lines: string[], field: FieldDef): void {
  const mapping = MOVE_TYPE_MAP[field.type];
  if (mapping.bcsPeel.startsWith('OPTION_')) {
    const innerType = field.type.replace('Option<', '').replace('>', '');
    const innerPeel = getInnerOptionPeel(innerType);
    lines.push(`    let ${field.name} = if (bcs::peel_bool(&mut reader)) {`);
    lines.push(`        option::some(${innerPeel})`);
    lines.push('    } else {');
    lines.push('        option::none()');
    lines.push('    };');
    return;
  }

  if (field.type === 'vector<String>') {
    lines.push(`    let ${field.name}_len = bcs::peel_vec_length(&mut reader);`);
    lines.push(`    let mut ${field.name} = vector::empty<String>();`);
    lines.push(`    let mut ${field.name}_i = 0;`);
    lines.push(`    while (${field.name}_i < ${field.name}_len) {`);
    lines.push(`        ${field.name}.push_back(std::string::utf8(bcs::peel_vec_u8(&mut reader)));`);
    lines.push(`        ${field.name}_i = ${field.name}_i + 1;`);
    lines.push('    };');
    return;
  }

  if (field.type === 'vector<address>') {
    lines.push(`    let ${field.name}_len = bcs::peel_vec_length(&mut reader);`);
    lines.push(`    let mut ${field.name} = vector::empty<address>();`);
    lines.push(`    let mut ${field.name}_i = 0;`);
    lines.push(`    while (${field.name}_i < ${field.name}_len) {`);
    lines.push(`        ${field.name}.push_back(bcs::peel_address(&mut reader));`);
    lines.push(`        ${field.name}_i = ${field.name}_i + 1;`);
    lines.push('    };');
    return;
  }

  lines.push(`    let ${field.name} = ${mapping.bcsPeel};`);
}

/** Get inner BCS peel expression for Option types */
function getInnerOptionPeel(innerType: string): string {
  switch (innerType) {
    case 'u64':
      return 'bcs::peel_u64(&mut reader)';
    case 'u128':
      return 'bcs::peel_u128(&mut reader)';
    case 'bool':
      return 'bcs::peel_bool(&mut reader)';
    case 'String':
      return 'std::string::utf8(bcs::peel_vec_u8(&mut reader))';
    default:
      return `/* TODO: peel ${innerType} */`;
  }
}

/** Collect which field types are used */
function fieldTypesUsed(fields: FieldDef[]): Set<string> {
  const used = new Set<string>();
  for (const f of fields) {
    if (f.type.startsWith('Option<')) {
      used.add('Option');
    }
    if (f.type === 'String' || f.type === 'Option<String>' || f.type === 'vector<String>') {
      used.add('String');
    }
    if (f.type === 'ID') {
      used.add('ID');
    }
  }
  return used;
}

function requiresCtx(schema: ActionSchema): boolean {
  return Boolean(schema.execution.needsCtx || schema.fields.some((f) => isResourceOut(f.role)));
}

function resourceLocalName(field: FieldDef, role: FieldRole): string {
  if (field.resourceVarName) return field.resourceVarName;
  if (field.name.endsWith('_resource')) return field.name.replace(/_resource$/, '');
  if (field.name.endsWith('_resource_name')) return field.name.replace(/_resource_name$/, '');
  if (field.name === 'resource_name') {
    return role === 'resource_in_object' ? 'object' : 'coin';
  }
  return `${field.name}_resource`;
}

function resourceMoveType(field: FieldDef, role: FieldRole, phantomTypes: string[]): string {
  if (field.moveType) {
    return role === 'resource_in_coin' || role === 'resource_out_coin'
      ? canonicalCoinType(field.moveType)
      : field.moveType;
  }

  const fallbackType = phantomTypes.length > 0 ? phantomTypes[0] : 'CoinType';
  return role === 'resource_in_coin' || role === 'resource_out_coin'
    ? `sui::coin::Coin<${fallbackType}>`
    : fallbackType;
}

function canonicalCoinType(moveType: string): string {
  const trimmed = moveType.trim();
  const coinMatch = trimmed.match(/^(?:sui::)?(?:coin::)?Coin<(.+)>$/);
  if (!coinMatch) return trimmed;
  return `sui::coin::Coin<${coinMatch[1].trim()}>`;
}

/** Generate the actual wrapped function call for Layer 3 */
function generateWrappedCall(lines: string[], call: WrappedCallDef, hasReturn: boolean): void {
  lines.push(`    // Call wrapped function: ${call.target}`);

  const typeParamsStr = call.typeParams.length > 0
    ? `<${call.typeParams.join(', ')}>`
    : '';

  const argStrs = call.args.map((arg) => arg.varName);

  const callExpr = `${call.target}${typeParamsStr}`;

  if (argStrs.length <= 3) {
    const argsInline = argStrs.join(', ');
    if (hasReturn) {
      lines.push(`    let call_result = ${callExpr}(${argsInline});`);
    } else {
      lines.push(`    ${callExpr}(${argsInline});`);
    }
  } else {
    if (hasReturn) {
      lines.push(`    let call_result = ${callExpr}(`);
    } else {
      lines.push(`    ${callExpr}(`);
    }
    for (let i = 0; i < argStrs.length; i++) {
      const comma = i < argStrs.length - 1 ? ',' : ',';
      lines.push(`        ${argStrs[i]}${comma}`);
    }
    lines.push('    );');
  }
}

/** Emit the remove_managed_asset call to borrow a cap from the Account */
function generateCapBorrow(lines: string[], cap: CapBorrowDef): void {
  lines.push('    // Borrow cap internally from account');
  const mutPrefix = cap.passStyle === 'mut_ref' ? 'mut ' : '';
  lines.push(`    let (${mutPrefix}${cap.varName}, ${cap.varName}_receipt) = access_control::remove_cap<Outcome, ${cap.capType}, _>(`);
  lines.push('        account,');
  lines.push('        registry,');
  lines.push('        executable,');
  lines.push('        ExecutionProgressWitness {},');
  lines.push('    );');
}

/** Emit the add_managed_asset call to return a cap to the Account */
function generateCapReturn(lines: string[], cap: CapBorrowDef): void {
  lines.push('    // Return cap to account');
  lines.push(`    access_control::return_cap<Outcome, ${cap.capType}, _>(`);
  lines.push('        account,');
  lines.push('        registry,');
  lines.push(`        ${cap.varName},`);
  lines.push(`        ${cap.varName}_receipt,`);
  lines.push('        executable,');
  lines.push('        ExecutionProgressWitness {},');
  lines.push('    );');
}

/** Emit borrow → wrapped call (with passStyle handling) → return */
function generateCapBorrowWithWrappedCall(
  lines: string[],
  cap: CapBorrowDef,
  call: WrappedCallDef,
  hasReturn: boolean,
): void {
  // Borrow cap
  generateCapBorrow(lines, cap);
  lines.push('');

  // Build arg strings, rendering cap_borrow args according to passStyle
  const typeParamsStr = call.typeParams.length > 0
    ? `<${call.typeParams.join(', ')}>`
    : '';

  const argStrs = call.args.map((arg) => {
    if (arg.source === 'cap_borrow') {
      switch (cap.passStyle) {
        case 'ref': return `&${cap.varName}`;
        case 'mut_ref': return `&mut ${cap.varName}`;
        default: return cap.varName;
      }
    }
    return arg.varName;
  });

  const callExpr = `${call.target}${typeParamsStr}`;

  // For value passStyle, the call returns the cap — need reassignment
  const needsCapReassign = cap.passStyle === 'value';
  // For value + resource_out, we'd need tuple destructuring — emit TODO
  const hasResourceOut = hasReturn;

  if (needsCapReassign && hasResourceOut) {
    lines.push('    // TODO: value passStyle + resource_out requires tuple destructuring');
  }

  lines.push(`    // Call wrapped function: ${call.target}`);

  // Determine what the call assigns to
  let assignPrefix = '';
  if (needsCapReassign && hasResourceOut) {
    // Rare: tuple destructuring needed
    assignPrefix = `let (${cap.varName}, call_result) = `;
  } else if (needsCapReassign) {
    assignPrefix = `let ${cap.varName} = `;
  } else if (hasResourceOut) {
    assignPrefix = 'let call_result = ';
  }

  if (argStrs.length <= 3) {
    const argsInline = argStrs.join(', ');
    lines.push(`    ${assignPrefix}${callExpr}(${argsInline});`);
  } else {
    lines.push(`    ${assignPrefix}${callExpr}(`);
    for (let i = 0; i < argStrs.length; i++) {
      const comma = i < argStrs.length - 1 ? ',' : ',';
      lines.push(`        ${argStrs[i]}${comma}`);
    }
    lines.push('    );');
  }

  lines.push('');

  // Return cap
  generateCapReturn(lines, cap);
}
